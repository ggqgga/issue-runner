# 루프 스크립트가 읽는 상수 — **한 자리** (#427 · 플랜 1단계)
# shellcheck shell=bash
#
# 사용: `. "$SCRIPT_DIR/lib/constants.sh"` (SCRIPT_DIR = scripts/ 절대경로).
# 형식은 전부 `: "${X:=값}"` 이다 — **환경변수가 이긴다**(테스트·운영 오버라이드가
# 종전 `${X:-값}` 과 똑같이 동작한다). 값이 비어 있는 채로 넘어오면 기본값이 든다.
#
# 왜 한 자리인가: 같은 경계를 두 스크립트가 각자의 기본값으로 들고 있으면 한쪽만
# 고쳐졌을 때 **스윕과 ① Reconcile 이 서로 다른 창에서 같은 워커를 살리고 죽인다**
# (ISSUE_TIMEBOX_HOURS 는 실제로 4벌이었다). 세 SKILL 의 `## 상수` 절은 이제 값을
# 다시 적지 않고 이 파일을 가리킨다 — 산문과 코드의 드리프트 원천을 없앤다.
# 값 자체를 바꿀 땐 여기만 고친다.

# ── 진행 증거·타임박스 (progress-evidence.sh · timebox-check.sh · finish-classify.sh) ──

# 커밋 신선도 임계(분). 원격 `agent/issue-<num>` 의 최신 커밋이 이보다 오래됐을 때만
# 커밋 쪽 진행 증거가 죽는다. 근거: bodat `bin/ci` 1회 실측 상한 ~570초(9.5분)에
# 박스 전역 직렬 CI 큐(#127) 대기 여유를 더한 값 — 워커가 CI 한 판을 기다리는 동안
# 새 커밋이 없는 것은 정상이므로 그 구간을 무진전으로 세면 안 된다.
: "${STALL_MIN:=25}"

# `agent:claimed` 부착 후 **진행 증거를 묻기 시작하는** 경과 시간(시간).
# 경과 초과 자체는 중단 사유가 아니다 — 넘긴 뒤에도 증거가 있으면 유예한다(#200).
: "${ISSUE_TIMEBOX_HOURS:=1}"

# 같은 claim 에서 허용하는 **누적 유예 횟수**(사이에 `unknown` 틱이 끼어도 리셋되지
# 않는다 — 세는 창은 claim 시각 이후 전부다). 넘으면 증거가 있어도 규칙대로 중단한다:
# 유예가 무한이면 진짜 좀비를 못 잡아 완화 자체가 새 구멍이 된다. 틱 간격 15분 기준
# 최대 ~45분의 추가 시간이라 실측(72분·64분) 형상을 덮으면서도 상한이 남는다.
: "${MAX_TIMEBOX_GRACE:=3}"

# 완결 유실 판별 시간버퍼(분). 살아있는 워커는 `검증자 리뷰:` 직후 수초 내 최종 판정을
# 찍으므로, 최신 검증자가 CLEAN 인데 이 버퍼를 넘도록 최종 판정이 없으면 워커 사망으로
# 본다. 진행 중 fix 루프는 최신 검증자 코멘트가 recent 이거나 non-CLEAN 이라 자동 제외.
: "${STALE_FINISH_MIN:=30}"

# ── 재개 스윕 (resume-sweep.sh) ────────────────────────────────────────────

# 멈춘 이슈를 다시 흘려보내기까지 기다리는 창(분). `hold:ladder` 이슈의 마지막 갱신이
# 이만큼 지나면 ① 의 재개 스윕이 집는다. `setup-labels.sh` 의 `hold:ladder` 설명이
# 이 상수명을 그대로 가리킨다(개명하면 그 설명이 없는 이름을 가리킨다, #364).
: "${RESUME_AFTER_MIN:=120}"

# 이슈 1건당 자동 재개 상한. 초과하면 재개 대신 `hold:policy` 승격 — 그때만 사람이다
# (무한 재시도 금지).
: "${LADDER_RESUME_LIMIT:=2}"

# ④ 정지 미러 정리가 **양성 증거를 못 얻은 채** 같은 건을 다시 시도하는 상한(#397).
# 회차는 상태 파일이 아니라 짝 이슈 코멘트의 `<!-- mirror-retry: <사유> pr=<n> -->`
# 마커 개수가 SSOT 다(`ladder-resume` 과 같은 규약). 닿으면 `mirror_retry_exhausted`.
: "${MIRROR_RETRY_LIMIT:=3}"

# ── 검증자 스폰 (codex-review-gate.sh · 세 SKILL 의 VERIFIER 데드라인) ──────

# codex 리뷰 게이트 1회의 벽시계 상한(초). **세 SKILL 의 `VERIFIER_TIMEOUT_MIN`
# (검증자 스폰 데드라인)도 이 값이다** — 분으로 환산해 쓴다(900초 = 15분).
# 종전 산문은 "`CODEX_GATE_TIMEOUT` 900s = `VERIFIER_TIMEOUT_MIN` 10분" 이라 적어
# 두 값이 어긋나 있었다(#427 — 600 ≠ 900). 값을 하나로 맞추고 이 한 자리에 둔다:
# 게이트가 900초를 기다리는데 스폰 데드라인이 10분이면 정상 리뷰를 `TaskStop` 으로
# 끊어 놓고 "미산출" 로 적게 된다. 늘리는 쪽(900)이 그 오판을 막는다.
: "${CODEX_GATE_TIMEOUT:=900}"
