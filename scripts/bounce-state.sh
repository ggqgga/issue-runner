#!/usr/bin/env bash
# bounce-state.sh <repo> <pr>
#
# 질문 하나에만 답한다: **이 PR 은 지금 반송(bounce) 회차 안인가.**
#
#   판정 규칙 한 줄: **최신 반송 마커 뒤에 오는 판정 코멘트(`머지 판정: ✅`/`⚠ 보류`/
#   `🔄`) 중 가장 늦은 것이 결과를 정한다.** 반송 마커가 없으면 `ok`, 반송 뒤 판정
#   코멘트가 하나도 없으면 `bounced`.
#
#   stdout `ok`      exit 0  반송 마커가 없거나, 반송 마커 뒤 마지막 판정이 ✅ 다
#                            → 마감 레인(closeout)이 만져도 된다
#   stdout `bounced` exit 0  최신 반송 마커 뒤에 판정 코멘트가 아직 없거나, 그중 마지막이
#                            `🔄`(교체 워커가 일을 재개했다) 다 → **워커 레인 소유**.
#                            closeout 은 무접촉이어야 한다
#   stdout `held`    exit 0  반송 마커 뒤 마지막 판정이 ⚠ 다
#                            (#218 attempt 2 — codex BLOCKER: 반송을 무조건 조기
#                            종료하면 반송 뒤 워커가 명시적으로 올린 보류 신호가 묻힌다.
#                            attempt 3 — codex BLOCKER: ✅ 의 *존재*만 보고 그 뒤에 더
#                            늦은 ⚠ 을 못 봐 `반송 → ✅ → ⚠` 이 `ok` 로 샜다. 늦은 쪽이
#                            이기도록 인덱스를 직접 비교해 고쳤다.
#                            attempt 4 — 마감 검증 BLOCKER: 후보 집합에 `🔄` 가 없어
#                            `held` 가 **한 번 걸리면 안 풀렸다**. 아래 "해제 경로" 절)
#                            **#218 두 번째 회차(사람 결정 (c)) — 이 값 자체(계산)는
#                            바뀌지 않았지만, closeout 스윕(gate 1)은 더 이상 이 값을
#                            "needs-human 승격" 신호로 쓰지 않는다.** 아래 "스윕 재부착
#                            폐지" 절 참조 — `bounced` 와 똑같이 무접촉으로 받아라.
#                            (finish-classify 자신의 `held` 행 — 반송 마커가 **없는**
#                            순수 ⚠ — 은 이 파일 밖의 별개 판정이라 영향받지 않는다.)
#   무출력           exit 1  판정 못 함(코멘트 조회·파싱 실패·인자 누락)
#
# 호출자 계약: **출력이 정확히 `ok` 일 때만 정상 진행**한다. `held`·`bounced`·판정
# 실패(exit 1) 는 **전부 같은 방향(무접촉)** 이다 — `held` 를 특별히 갈라 needs-human
# 으로 승격하던 계약은 #218 두 번째 회차에서 폐지됐다(아래 "스윕 재부착 폐지" 절).
# 판정 실패(exit 1)와 `bounced` 를 같은 방향(무접촉)으로 받는
# 것이 fail-closed 다: 반송되지 않았음을 *증명하지 못한* 상태를 통과로 처리하면 그게
# fail-open 이다(PR#139 교훈 — 빈 결과와 실패를 구분하고, 실패는 가드 분기로 보내라).
#
# ── 왜 스크립트로 뽑았나 (#196) ──────────────────────────────────────────
# 소비자가 둘이고 실행 주체가 다르다:
#   1. `closeout-eligible.sh` — ✅ 정상 후보 필터의 마지막 관문(셸에서 호출)
#   2. `skills/closeout/SKILL.md` ①-b 의 **CONFLICTING 입양** 경로 — 프로즈가 이 스크립트를
#      직접 부른다. ①-b 는 `finish-classify.sh` 를 일부러 건너뛰므로(다른 갈래가 적용
#      안 됨) 반송 판정만 따로 빌릴 자리가 필요했다.
# `finish-classify.sh` 에 출력 하나를 더 얹는 길도 있었지만 택하지 않았다 — 거기 다섯
# 출력은 "완결 유실 상태" 라는 한 축의 값이고, 반송 여부는 **직교하는 다른 축**이다.
# 한 stdout 에 두 축을 섞으면 소비자가 문자열로 축을 다시 갈라야 한다(PR#168 교훈:
# 사유가 여럿인데 공유 센티널 하나만 보면 조용히 오분류된다). 그래서 축마다 한 자리다.
#
# 반대로 **마커 집합과 선후 판정은 절대 두 벌로 두지 않는다** — 예전에 채널마다 가드를
# 베껴 한쪽(verify-runner 채널)이 빠진 채 fail-open 이었다(#171). 그 한 자리가 여기다.
#
# ── env 오버라이드 ──────────────────────────────────────────────────────
#   BOUNCE_COMMENTS_FILE  코멘트 배열 JSON(`[{body,createdAt},...]`)이 담긴 **파일 경로**.
#                         이미 코멘트를 읽은 호출자가 중복 gh 조회를 피하는 통로
#                         (finish-classify 의 FC_COMMENTS_FILE 과 같은 계약: 파일인 이유는
#                         전량 코멘트가 exec 인자 한계 128KB 를 넘을 수 있어서다).
#                         읽기 실패·빈 파일은 **실조회로 새지 않고** exit 1 이다 — 호출자가
#                         "이 파일이 곧 판정 입력" 이라 계약한 이상 다른 출처로 조용히
#                         갈아타면 무엇으로 판정했는지 알 수 없다. 코멘트 0건은 `[]` 로
#                         오며, 그건 정상 판정(`ok`)이라 빈 문자열과 구분한다.
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

repo=${1:-}
pr=${2:-}
[ -n "$repo" ] && [ -n "$pr" ] || exit 1

# ── 반송(bounce) 마커 집합 — 한 자리 (#171 · #196 · #212) ────────────────
# PR 을 워커에게 되돌리는 채널이 둘이고, 각자 자기 어휘로 코멘트를 남긴다:
#   `재디스패치`   closeout 마감 검증 BLOCKER·완결 유실 반송 (skills/closeout/SKILL.md)
#   `재검증 실패`  verify-runner 재검증 반려          (skills/verify-runner/SKILL.md)
# 두 채널의 효과는 같다 — 교체 워커가 새 커밋을 올리기 전까지 head 가 그대로라, 그
# 이전에 찍힌 ✅ 가 살아 남아 "방금 반려된 PR" 을 머지·입양 후보로 만든다. 그래서
# **한 집합**으로 다룬다. 새 반송 어휘가 늘면 **이 배열 한 곳만** 고쳐라 — 채널마다
# 가드를 베끼면 하나 빠진 채로 fail-open 이 된다(실제로 verify-runner 채널이 그렇게
# 빠져 있었다). 두 마커 모두 한/영 SKILL 이 같은 한글 문자열을 찍는다(SKILL.en.md 도
# 동일) — 영문 변종이 생기면 여기에 함께 넣는다.
#
# 매칭 규칙은 두 조건의 곱이다 — **위치**와 **낱말 경계**:
#
#   ⑴ 마커가 코멘트 **문자열 시작(=첫 줄 맨 앞)** 에 있어야 한다(#212).
#      콜론을 리터럴로 요구하지 않는다 — 콜론을 배열에 넣어 두면(`재디스패치:`) 워커가
#      실제로 남기는 `재디스패치 attempt N — …` 같은 변형이 리터럴 불일치로 빠져나가
#      안전망이 조용히 샌다(실사고: PR #202). 그렇다고 부분 문자열 포함(`contains`)으로
#      넓히면 결함을 설명하며 본문 중간에 단어만 인용한 코멘트까지 반송으로 잡히므로,
#      위치는 시작으로 고정한다 — 중간 인용은 위치가 0 이 아니라 자동으로 빠진다.
#
#   ⑵ 마커 **뒤에 남는 꼬리**(`$t` — 첫 줄에서 마커를 뗀 나머지)의 형태로 가른다
#      (#221 이 세우고 #251 이 두 축을 닫으며 한 술어로 다시 썼다). 세 갈래다:
#
#      ⒜ **반송 관용 구분자**로 시작한다 — `:` · 공백?+`#` · 공백?+`(` · 공백?+대시 ·
#         공백?+숫자 · 줄 끝/개행 → **무조건 반송**. `bounce-comment.sh` 가 찍는 기계
#         채널 본문(`마커: #N — 사유`)이 전부 여기 들어오므로 ⒝ 의 어떤 예외로도
#         안 샌다(불가침 — 격자가 `: … 해소 요망`·` #193 … 해소 요망` 으로 못박는다).
#
#      ⒝ **산문이 이어진다** — 한글 음절이 바로 붙거나(조사·어미: `재디스패치가 …`)
#         공백 뒤에 낱말이 온다(`재디스패치 필요 여부를 …`). 마커가 문장 안 한 낱말로
#         쓰인 것이므로 여기서만 두 축을 가른다:
#           · 꼬리에 **해소 보고 표식**(`완료`·`해소`, 부정 접두 `미`/`불` 제외)이
#             있으면 **반송 아님**. 원장 실측(세 레포 최근 PR 141건 중 마커로 시작하는
#             첫 줄 58건)에서 이 형태 6건은 **전부** 반송이 아니라 워커의 **반송 해소
#             보고**였다(`재디스패치 attempt 2 — … 해소.`). 옛 규칙은 이걸 `bounced` 로
#             읽어 아무도 반송하지 않은 PR 을 마감 후보에서 뺐다(#251 ② fail-closed).
#           · 없으면 꼬리에 **반송 표식**(`#숫자` · `attempt` · 대시 · `반송`)이 있을
#             때만 반송. 옛 규칙은 한글이 이어지기만 하면 무조건 통과시켜, 사람이 손으로
#             쓴 `재검증 실패로 반송합니다 — #193` 이 `ok` 로 샜다(#251 ① fail-open).
#             표식이 전혀 없는 `…가 필요한지 확인했습니다`·`…를 분석합니다` 는 종전대로
#             반송이 아니다 — #221 이 없앤 정체를 되살리지 않는다.
#
#      ⒞ 그 밖(공백 없이 문장부호·라틴이 부착: `재디스패치[attempt 3] — 사유`) → 반송.
#
# ⒜ 를 열거로 두고도 fail-open 이 아닌 이유: 열거 밖으로 새는 형태는 ⒝ 의 **반송 표식**이
# 다시 받는다(` [attempt 3] — 사유` 는 ⒞, ` 3회차` 는 ⒜ 의 숫자, ` — 사유` 는 ⒜ 의 대시).
# 두 겹이라 #212 가 막은 사고(반송된 PR 이 머지 후보로 되올라옴)로 되돌아가지 않는다.
#
# ⑵ 의 값과 대가를 정확히 적는다(둘 다 사실이다 — 한쪽만 적으면 다음 사람이 이 자리를
# 안 의심한다):
#   · **근사인 것**: `완료`·`해소` 어휘로 해소 보고를 가르는 것은 근사다. 네 겹으로
#     좁힌다 — ⑴ 기계 채널(⒜ 콜론 형태)은 예외의 사정권 밖이고, ⑵ 부정 접두
#     (`미해소`·`불완료`)는 해소로 안 세고, ⑶ **요구 어휘가 뒤에 붙으면**
#     (`해소 요망`·`해소 필요`·`해소 바람`·`해소해 주세요`) 보고가 아니라 해소를
#     *요구하는* 반송이라 예외가 안 걸리고(사전 리뷰가 이 칸으로 ① 이 새는 것을 실측해
#     잡았다), ⑷ 손으로 쓴 반송이라도 `#N`·`(`·대시·숫자로 시작하면 ⒜ 가 먼저 잡는다.
#     그래도 남는 근사는 있다 — 한 줄에 진짜 완료 보고와 요구 어휘가 **함께** 있으면
#     `bounced` 로 떨어진다(정체 방향으로 기운다).
#   · **fail-closed 로 남긴 것**: `재디스패치 반송 규칙을 정리했습니다` 처럼 반송 표식
#     어휘(`반송`)를 본문에 담은 평범한 문장은 `bounced` 로 정체한다. 이 축은 유실이
#     정체보다 나쁘므로(반송 유실 = 반송 사유가 된 코드가 그대로 머지) 이 방향으로
#     골랐다. 정체는 다음 판정성 코멘트 한 건으로 풀린다.
#   · **여전히 참인 계약**: 반송 코멘트는 `bounce-comment.sh` 로만 남긴다(그 헬퍼는 항상
#     `마커:` 를 찍어 ⒜ 로 떨어진다). `bin/ci` 가 헬퍼 생성 본문을 이 스크립트에 먹여
#     `bounced` 가 나오는지로 매번 확인한다. #251 이 ⒝ 로 손 코멘트까지 덮었지만 그건
#     안전망의 두 번째 겹이지 계약의 대체가 아니다.
#
# 전수 격자는 `scripts/tests/bounce-state.test.sh` 의 `want` 열에 못박혀 있다(PR#202 교훈).
# 두 축의 가드는 각각 `# MUT-1`(①)·`# MUT-2`(②) 주석이 달린 **결과식 줄**이고, 테스트가
# 그 한 줄만 옛 값으로 되돌린 사본을 만들어 **서로 다른 케이스가 빨개지는지**를 실측한다
# (앵커는 `($bmark` 로 시작하는 코드 형태까지 요구하고, 바뀐 줄이 정확히 1 인지도 센다 —
# 이 설명 문장까지 물어 뮤턴트에 벌거벗은 `false` 가 주입되지 않게).
# 두 결과식은 문자 그대로 같다(`$bmark and ($resolved | not)`) — 뮤테이션이 가르는 것은
# 분기 **선택자**이지 결과식이 아니다. 공유 술어(`$bmark`·`$resolved`)가 회귀하면 두 축이
# 동시에 빨개진다. 그건 근사를 한 자리에 모은 대가고, 격자의 `want` 열이 그 자리를 문다.
#
# 새 마커를 배열에 넣을 때: ⒝ 의 "한글이 이어짐" 은 **한글 음절만** 센다. 라틴 문자
# 마커(예 `Redispatch`)를 추가하면 굴절형(`Redispatched`)이 ⒞ 로 떨어져 여전히
# `bounced` 다 — 안전한 방향이므로 그대로 두되, 의도적으로 배제하고 싶은 굴절형이
# 있으면 마커를 그 형태까지 적어 넣어라. 그리고 마커 자신에 표식 어휘(`반송`·`완료`
# 등)가 들어가면 안 된다 — 표식은 마커를 **뗀 뒤의 꼬리**에서만 센다(그래서 마커
# 문자열 자체는 판정에 안 섞인다).
BOUNCE_MARKERS='["재디스패치","재검증 실패"]'

# ── 입력 수집 ───────────────────────────────────────────────────────────
if [ -n "${BOUNCE_COMMENTS_FILE:-}" ]; then
  comments=$(cat "$BOUNCE_COMMENTS_FILE" 2>/dev/null) || exit 1
else
  # 코멘트는 **페이지네이션 전량**으로 읽는다(#171 [P1-2] · #173).
  # `gh pr view --json comments` 는 첫 100건만 준다 — 반송을 여러 번 도는 PR 은
  # 워커·verify·closeout 코멘트가 겹겹이 쌓여 100건이 먼 숫자가 아니고, 마커가
  # 101번째 이후면 안전망이 통째로 눈이 먼다. 조회 로직은 pr-comments.sh 한 자리다.
  # 조회 실패(exit 1)는 그대로 전파한다 — 부분 출력을 정상값으로 채택하지 않는다.
  comments=$("$SCRIPT_DIR/pr-comments.sh" "$repo" "$pr" 2>/dev/null) || exit 1
fi
# 빈 문자열 = 입력을 못 받음(≠ 코멘트 0건 `[]`). 판정하지 않는다.
[ -n "$comments" ] || exit 1

# ── 선후 판정 ───────────────────────────────────────────────────────────
# 선후는 **코멘트 배열의 마지막 매칭 인덱스**로 잰다 — createdAt 이 아니라.
# GitHub 코멘트 시각은 초 단위라 ✅ 직후 같은 초에 반송 마커가 달리면 두 값이 같아져
# 시각 비교(`>`)가 거짓이 되고 반송된 PR 이 통과한다. 반대로 같은 초에 마커 뒤 새 ✅ 가
# 달린 정상 재완결은 통과해야 하므로, 단순 시각 비교로는 양방향을 못 가린다. 코멘트
# 배열은 GitHub 이 생성 순으로 주므로(pr-comments.sh 의 순서 계약) 인덱스가 그 순서를
# 그대로 담는다 — 초 단위로 뭉개지지 않는 유일한 값(PR#168 교훈: 정보를 담을 수 있는
# 값으로 바꿔라).
#
# 대조 대상을 `머지 판정: ✅` 로 **좁게** 잡는 것은 의도다. 이슈 #196 이 적은 판별식은
# "판정성 코멘트(머지 판정·검증자 리뷰·재검증 실패·재디스패치) 중 마지막이 반송
# 마커면 워커 레인 소유" 인데, 그 넓은 집합으로 재면 반송 **뒤에 달린 🔄·검증자 리뷰**
# (= 교체 워커가 지금 일하는 중이라는 가장 강한 증거)가 반송을 덮어 `ok` 가 된다.
# ✅ 하나만 반송을 해제하게 두면 두 형상 모두 안전한 쪽으로 떨어진다 — 사고 재현
# 픽스처(✅ 0건)도 종전 규약(반송 뒤 새 ✅ 면 복귀)도 같은 식으로 맞는다.
#
# ── held(#218 attempt 2·attempt 3) ────────────────────────────────────
# attempt 1 은 `bi > vi`(✅ 없음 포함)를 전부 `bounced` 하나로 묶어 무조건 조기
# 종료했다 — codex BLOCKER: 반송 뒤 교체 워커가 명시적으로 올린 `머지 판정: ⚠ 보류`
# 조차 영원히 안 보여 needs-human 승격이 묻힌다("Moving the bounce gate ahead of all
# classification permanently excludes... a later ⚠ verdict never becomes held").
# attempt 2 는 이 구멍을 `$vi != null and $bi <= $vi` 로 막으려 했지만, 이건 **✅ 의
# 존재만** 보고 그 뒤에 더 늦은 ⚠ 이 있는지는 안 본다 — `반송 → ✅ → ⚠` 배열에서
# `$bi <= $vi` 가 먼저 참이 되어 `ok` 로 빠지고 `held` 분기(그 아래 elif)에 아예
# 도달하지 못했다(attempt 3 BLOCKER). 사람이 봐야 한다고 방금 올라온 판정이 그렇게
# closeout 의 자동 rebase·입양 경로로 샌다.
#
# 규칙(말로): **반송 마커 이후에 오는 종결 판정(✅/⚠) 중 가장 늦은 것이 결과를
# 정한다.** 반송 마커가 없으면 ok. 반송 이후 종결 판정이 없으면 bounced. 그래서
# ✅ 와 ⚠ 를 "존재하느냐" 가 아니라 **반송 뒤 인덱스끼리 직접 비교**한다 — 반송 뒤에
# 온 것 중 인덱스가 더 큰(=더 늦은) 쪽이 이긴다. `bi`·`vi`·`hi` 모두 같은 배열의 마지막
# 매칭 인덱스(createdAt 아님, 초 단위로 뭉개지는 문제는 위 코멘트 참조)라 새 술어를
# 만드는 게 아니라 같은 판정 규칙을 ⚠ 에도 대칭으로 적용하는 것뿐이다.
# 단, `held` 은 `ok` 가 아니다 — 마감 레인이 `stale_reverify` 재디스패치로 새지
# 않도록 호출자가 별도로 갈라야 한다(살아있는 교체 워커와 충돌하는 건 재디스패치
# 쪽이지 needs-human 쪽이 아니다).
#
# ── 해제 경로(#218 attempt 4 — 마감 검증 BLOCKER) ──────────────────────
# attempt 2·3 이 세운 `held` 는 **진입만 있고 해제가 없었다.** 후보 집합이 ✅·⚠ 둘뿐
# 이라 `머지 판정: 🔄` 가 빠져 있었고, 그래서 이 순서가 오면 매 틱 되풀이됐다:
#   ⑴ 반송 마커 ⑵ 워커 `⚠ 보류` → closeout 이 `held` → `needs-human`+`hold:policy`
#   ⑶ **사람이 그 보류를 풀어 라벨을 뗀다** ⑷ 교체 워커가 `🔄` 를 찍고 재개한다
#   ⑸ 다음 틱: `needs-human` 이 없으니 다시 스윕 대상인데 판정이 **여전히 `held`**
#      → `closeout-blocked` 가 다시 걸려 **사람이 방금 푼 보류가 되살아나고 살아있는
#      교체 워커가 끊긴다.** `✅` 에 도달해야만 풀리는데 끊기니까 도달할 수 없다.
# 이 레포가 명시적으로 막아 온 "루프 대 사람 싸움"(#151)의 방향만 바뀐 형태고, 이
# 게이트는 closeout 이 **매 틱** 실행하는 자리라 회귀가 조용히 반복된다.
#
# 그래서 규칙은 그대로 두고 **후보 집합만 대칭으로 채운다** — `🔄` 도 판정 코멘트이니
# 같은 "가장 늦은 것이 이긴다" 에 참여시킨다. 결과값은 `ok` 가 **아니라** `bounced` 다:
# `🔄` 는 "교체 워커가 지금 일하는 중" 이라는 가장 강한 증거이므로 워커 레인 소유다
# (`ok` 로 두면 attempt 1 이 막은 "CONFLICTING 갈래가 살아있는 워커 PR 을 입양·rebase"
# 가 그대로 되돌아온다). 새 술어를 만드는 게 아니라 후보가 하나 늘 뿐이다.
#
# 교훈(레포 공통): **새 종결 상태를 만들 때는 진입 경로만 보지 말고 해제 경로까지
# 함께 세워라.** 진입만 보면 그 상태가 사람의 해제를 매 틱 되돌린다.
#
# ── 스윕 재부착 폐지(#218 두 번째 회차 — 마감 검증 BLOCKER, 사람 결정 (c)) ──────
# attempt 4 의 해제 경로는 **교체 워커가 이미 `🔄` 를 찍은 뒤**만 고친다. 그런데
# ⑶ 사람이 라벨을 떼는 시점과 ⑷ 교체 워커가 `🔄` 를 찍는 시점 사이에는 **창이 있다**
# — 그 창 안에서는 코멘트 배열이 ⑵ 시점과 한 글자도 다르지 않으므로(아직 아무도
# 새 코멘트를 안 남겼다), 이 함수는 여전히 `held` 를 낸다. `bounce-state.sh` 는 코멘트
# 배열의 순수 함수라 "이 `held` 를 스윕이 이미 한 번 소비해 needs-human 을 붙였다가
# 사람이 방금 뗐다" 와 "이 `held` 를 스윕이 아직 한 번도 못 봤다" 를 **구분할 수
# 없다** — 둘 다 같은 문자열이다. 코멘트 밖의 신호(타임라인 이력·해제 마커)로
# 가르는 안도 검토됐으나 채택되지 않았다(PR #225 사람 결정 — 해제 마커는 사람이
# 라벨만 떼면 바로 깨지고, 타임라인 이력은 #174 의 에피소드 키가 다루는 더 넓은
# 축이다).
#
# 그래서 (c): **closeout 스윕(gate 1, `skills/closeout/SKILL.md` ①-b)은 이 함수의
# `held` 출력을 더 이상 needs-human 승격 신호로 쓰지 않는다** — `bounced`·판정
# 실패와 똑같이 **무접촉**으로 받는다. 되살아나는 것을 알고 고른 선택이다: attempt 2
# 가 막았던 원래 사고(반송 뒤 ⚠ 가 영영 needs-human 이 안 되는 것)가 **이 게이트
# 자리에서는** 되살아난다. 대신 살아남는 경로가 있다 — **반송 마커가 전혀 없는**
# 순수 ⚠(`$bi == null` → 이 함수는 애초에 `ok` 를 낸다)은 이 게이트를 `ok` 로 통과해
# `finish-classify.sh` 자신의 `held` 분류(SKILL.md 2절 표)로 그대로 승격된다. 그
# 경로는 이 회차가 손대지 않았다(#174 소유 파일). 단 그 경로에도 사람이 라벨을 뗀 뒤
# 같은 ⚠ 로 다음 스윕이 홀드를 되붙이는 창은 남는다 — 그 해제 판정(부착↔해제
# 에피소드)은 #174(PR #182)가 `finish-classify.sh` 에서 닫는다.
#
# **이 함수의 `held` 계산 자체는 바뀌지 않는다** — 값은 여전히 정확하고(#218 attempt
# 2·3 이 세운 선후 규칙 그대로), 다른 소비자(예: 향후 #174 계열의 에피소드 키 판정)가
# 필요하면 그대로 쓸 수 있게 남겨 둔다. 폐지되는 것은 "이 특정 호출자(closeout 스윕)가
# 이 값을 어떻게 조치하는가" 뿐이다 — 조치는 `bounce-state.sh` 밖(SKILL.md 프로즈)의
# 계약이라 이 파일은 그 계약을 문서로만 반영한다.
state=$(printf '%s' "$comments" | jq -r --argjson bm "$BOUNCE_MARKERS" '
  [.[].body] as $bodies
  | ([ $bodies | to_entries[]
       | select(.value as $x
           | (($x | split("\n") | .[0]) // "") as $line
           | ($bm | any(. as $m |
               ($line | startswith($m))
               and (($line[($m | length):]) as $t
                    # 반송 표식(#251 ①) — 조사가 붙어도 이게 있으면 반송이다.
                    # 하이픈 `-` 은 일부러 뺐다: `fail-open` 같은 낱말이 표식이 된다.
                    | ($t | test("#[0-9]|attempt|[–—]|반송"; "i")) as $bmark
                    # 해소 보고 표식(#251 ②) — 부정 접두(`미`·`불`)가 붙으면 해소가
                    # 아니고, 뒤에 **요구 어휘**가 붙으면(`해소 요망`·`해소해 주세요`)
                    # 그건 보고가 아니라 해소를 **요구하는 반송**이다(사전 리뷰 BLOCKER).
                    | (($t | test("(^|[^미불])(완료|해소)"))
                       and (($t | test("(완료|해소)(해|하|되)?\\s*(요망|필요|바람|바랍|요청|주세|주시|하라|해라|해야|어야|부탁|권장)")) | not)) as $resolved
                    | if ($t | test("^(:|\\s*$| ?[0-9]| ?#| ?\\(| ?[-–—])")) then true
                      elif ($t | test("^[가-힣ㄱ-ㅎㅏ-ㅣ]")) then
                        ($bmark and ($resolved | not))   # MUT-1: ① 조사·어미가 붙은 진짜 반송
                      elif ($t | test("^\\s")) then
                        ($bmark and ($resolved | not))   # MUT-2: ② 공백 뒤 산문(해소 보고·평범한 명사)
                      else true
                      end))))
       | .key ] | last) as $bi
  | ([ $bodies | to_entries[]
       | select(.value | startswith("머지 판정: ✅") or startswith("Merge verdict: ✅"))
       | .key ] | last) as $vi
  | ([ $bodies | to_entries[]
       | select(.value | startswith("머지 판정: ⚠") or startswith("Merge verdict: ⚠"))
       | .key ] | last) as $hi
  | ([ $bodies | to_entries[]
       | select(.value | startswith("머지 판정: 🔄") or startswith("Merge verdict: 🔄"))
       | .key ] | last) as $pi
  # 반송 뒤(>bi)에 실제로 온 판정만 후보로 삼는다 — bi 앞에 낡게 남은 ✅/⚠/🔄 는
  # 무의미하므로 존재 여부가 아니라 "반송보다 늦었는가" 로 먼저 걸러낸다.
  | (if $vi != null and $vi > $bi then $vi else null end) as $v_after
  | (if $hi != null and $hi > $bi then $hi else null end) as $h_after
  | (if $pi != null and $pi > $bi then $pi else null end) as $p_after
  # 후보 중 인덱스가 가장 큰(=가장 늦은) 것이 이긴다. 후보가 없으면 bounced.
  | if   $bi == null then "ok"
    else ([
            {i:$p_after, s:"bounced"},   # MUT-P: 해제 경로 후보(#218 attempt 4)
            {i:$v_after, s:"ok"},
            {i:$h_after, s:"held"} ]      # 값 계산은 그대로 — 스윕이 이 값을 더 이상
                                          # 승격에 안 쓸 뿐(#218 두 번째 회차, 위
                                          # "스윕 재부착 폐지" 절)
          | map(select(.i != null)) | sort_by(.i) | last
          | if . == null then "bounced" else .s end)
    end' 2>/dev/null) || exit 1

# jq 가 성공해도 형상이 어긋나면(빈 출력·예상 밖 값) 판정으로 인정하지 않는다.
case "$state" in
  ok|bounced|held) printf '%s\n' "$state" ;;
  *) exit 1 ;;
esac
